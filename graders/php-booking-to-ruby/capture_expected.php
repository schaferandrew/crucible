<?php
/**
 * Captures the PHP reference's answers to the hidden tests' requests into expected_outputs.py.
 *
 * Run from the Crucible checkout with PHP 8.1 or later:
 *
 *   php graders/php-booking-to-ruby/capture_expected.php
 *
 * It runs every request in REQUESTS through repos/php-booking-to-ruby/app.php (in process, like
 * tests/run_tests.php does) and rewrites expected_outputs.py beside this file. Add a request here
 * before a hidden test uses it, then re-run. `git diff` on expected_outputs.py should then be empty
 * unless the seeded app changed.
 */
const REQUESTS = [
    '/rooms',
    '/rooms.html',
    '/room?id=0101',
    '/bookings',
    '/bookings/all',
    '/bookings?room=102',
    '/report',
    '/quote?room=101&checkin=03/09/2024&nights=2&guests=1',
    '/quote?room=101&checkin=2024-03-05&nights=2&guests=0',
    '/quote?room=101&checkin=2024-03-05&nights=2&guests=1',
    '/quote?room=101&checkin=2024-03-10&nights=1&guests=1',
    '/quote?room=101&checkin=2024-03-12&nights=1&guests=1',
    '/quote?room=102&checkin=2024-02-30&nights=1&guests=2',
    '/quote?room=102&checkin=2024-03-05&nights=3.7&guests=2',
    '/quote?room=102&checkin=2024-03-12&nights=1&guests=4',
    '/quote?room=102&checkin=2024-03-12&nights=3&guests=2',
    '/quote?room=201&checkin=2024-03-12&nights=1&guests=1',
    '/quote?room=301&checkin=2024-03-12&nights=1&guests=9',
    '/quote?room=301&checkin=2024-03-12&nights=3&guests=2&coupon=STAFF',
    '/quote?room=401&checkin=2024-03-12&nights=2&guests=4&coupon=spring10',
    '/quote?room=999&checkin=2024-03-12&nights=1&guests=1',
];

require __DIR__ . '/../../repos/php-booking-to-ruby/app.php';

$expected = [];
foreach (REQUESTS as $request) {
    list($status, $body) = handle($request);
    $expected[$request] = [
        'status' => $status,
        'body' => substr($request, -5) === '.html' ? $body : json_decode($body),
    ];
}

$json = json_encode($expected, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_PRESERVE_ZERO_FRACTION);
$py = <<<PY
"""The PHP reference's answers to the hidden tests' requests: {request: {"status": ..., "body": ...}}.

Generated by capture_expected.php (php graders/php-booking-to-ruby/capture_expected.php); don't edit by hand.
A JSON body is the parsed value (the tests compare parsed JSON), an HTML body the exact text.
"""
import json

EXPECTED = json.loads(r'''
$json
''')

PY;
file_put_contents(__DIR__ . '/expected_outputs.py', $py);
echo 'wrote expected_outputs.py (', count($expected), " requests)\n";
