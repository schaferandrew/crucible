"""The bundle manifest: which runs a bundle holds, and the one rule set that decides what publishing may do.

`<bundle>/manifest.json` is generated by `crucible publish` and read by `publish --check`, and later by
the community-submission bot and CI. This module is pure (no file or network access, no clocks), so all
of them apply the same rules:

  unknown run_uuid                    -> add
  same run_uuid, same content_hash    -> no-op
  same run_uuid, different hash       -> reject (a published run is never overwritten)
  null hashes (legacy runs)           -> "same" only when the files are byte-identical

New score records and appended status records for a run already in the manifest stay allowed; they are
not part of the run's identity. See docs/bundle-format.md#the-manifest.
"""
from __future__ import annotations

import json

FILE = "manifest.json"
FORMAT_VERSION = 4

ADD, NOOP, REJECT = "add", "noop", "reject"


def empty() -> dict:
    return {"record": "manifest", "format_version": FORMAT_VERSION, "runs": {}}


def entry(content_hash: str | None, path: str, submitter: str | None = None,
          scores: list[str] | None = None, status_count: int = 0) -> dict:
    return {"content_hash": content_hash, "submitter": submitter, "path": path,
            "scores": sorted(scores or []), "status_count": status_count}


def submitter_of(record: dict) -> str | None:
    """Who a record says submitted it (format 3's provenance.submitter), as a plain string."""
    sub = (record.get("provenance") or {}).get("submitter")
    if isinstance(sub, dict):
        sub = sub.get("login") or sub.get("name")
    return sub if isinstance(sub, str) and sub else None


def decide(existing: dict | None, content_hash: str | None, identical_bytes: bool | None = None) -> tuple[str, str | None]:
    """(ADD | NOOP | REJECT, why) for a run arriving with `content_hash`, against its manifest entry (or None).

    `identical_bytes` says whether the incoming file equals the published one byte for byte; it only
    matters when both hashes are null.
    """
    if existing is None:
        return ADD, None
    old = existing.get("content_hash")
    if old is not None and old == content_hash:
        return NOOP, None
    if old is None and content_hash is None:
        if identical_bytes:
            return NOOP, None
        return REJECT, "published without a content hash and the file differs byte for byte"
    return REJECT, f"already published with hash {old} but this copy hashes to {content_hash}"


def dump(manifest: dict) -> str:
    """The file's text: sorted keys, one indent, UTF-8, a trailing newline: the same bytes every time."""
    return json.dumps(manifest, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def problems(manifest, found: dict[str, dict]) -> list[str]:
    """What's wrong with a manifest next to the files on disk.

    `found` maps run_uuid -> {"content_hash", "path", "scores": [names], "status_count"} as read from the
    files themselves. Reports a run missing from disk, a run on disk the manifest doesn't list, and any
    field that disagrees.
    """
    if not isinstance(manifest, dict) or manifest.get("record") != "manifest" or not isinstance(manifest.get("runs"), dict):
        return ["manifest.json: not a manifest record"]
    runs, out = manifest["runs"], []
    for uuid in sorted(runs):
        if uuid not in found:
            out.append(f"manifest.json: {uuid} is listed but its run file is missing")
            continue
        want, have = runs[uuid], found[uuid]
        if want.get("content_hash") != have.get("content_hash"):
            out.append(f"manifest.json: {uuid} content hash {want.get('content_hash')} doesn't match its file's {have.get('content_hash')}")
        if want.get("path") != have.get("path"):
            out.append(f"manifest.json: {uuid} path {want.get('path')} isn't where it is ({have.get('path')})")
        if sorted(want.get("scores") or []) != sorted(have.get("scores") or []):
            out.append(f"manifest.json: {uuid} score records differ from the files")
        if want.get("status_count", 0) != have.get("status_count", 0):
            out.append(f"manifest.json: {uuid} status count {want.get('status_count')} but {have.get('status_count')} on disk")
    out += [f"manifest.json: {uuid} has a run file but isn't listed" for uuid in sorted(set(found) - set(runs))]
    return out
